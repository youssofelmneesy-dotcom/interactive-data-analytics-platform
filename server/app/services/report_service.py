def create_report_config(
    dataset_id: str,
    title: str,
    description: str | None = None,
    section_types: list[str] | None = None,
    include_charts: bool = True,
    include_insights: bool = True,
) -> dict[str, Any]:
    """Create a report configuration and generate the PDF.

    Args:
        dataset_id: Dataset identifier.
        title: Report title.
        description: Optional report description.
        section_types: Types of sections to include.
        include_charts: Whether to include saved charts.
        include_insights: Whether to include AI insights.

    Returns:
        Report metadata with download URL.
    """
    dataset = get_dataset(dataset_id)
    sections: list[dict[str, Any]] = []

    # Always include summary
    sections.append({
        "type": "summary",
        "title": "Executive Summary",
        "content": description or f"Analysis report for {dataset['name']}",
    })

    # Include insights if requested
    if include_insights:
        insights = list_insights(dataset_id)
        if insights:
            sections.append({
                "type": "insight",
                "title": "AI-Generated Insights",
            })

    # Include charts if requested
    if include_charts:
        charts = list_chart_configs(dataset_id)
        for chart in charts[:5]:  # Limit to 5 charts
            sections.append({
                "type": "chart",
                "title": f"Chart: {chart['title']}",
                "chartId": chart["id"],
            })

    # Include data preview table
    sections.append({
        "type": "table",
        "title": "Data Preview",
    })

    # Generate PDF
    pdf_path = generate_pdf_report(dataset_id, title, sections)

    return {
        "id": Path(pdf_path).stem,
        "datasetId": dataset_id,
        "title": title,
        "description": description,
        "filePath": pdf_path,
        "sections": sections,
        "status": "completed",
        "createdAt": datetime.now(timezone.utc).isoformat(),
    }


def list_reports(dataset_id: str) -> list[dict[str, Any]]:
    """List all generated reports for a dataset."""
    with db_session() as conn:
        rows = conn.execute(
            """
            SELECT id, dataset_id, title, file_path, created_at
            FROM reports
            WHERE dataset_id = ?
            ORDER BY created_at DESC
            """,
            (dataset_id,),
        ).fetchall()

    return [
        {
            "id": row["id"],
            "datasetId": row["dataset_id"],
            "title": row["title"],
            "filePath": row["file_path"],
            "createdAt": row["created_at"],
        }
        for row in rows
    ]


def get_report(report_id: str) -> dict[str, Any]:
    """Get a single report by ID."""
    with db_session() as conn:
        row = conn.execute(
            "SELECT id, dataset_id, title, file_path, created_at FROM reports WHERE id = ?",
            (report_id,),
        ).fetchone()

    if row is None:
        raise NotFoundError(f"Report '{report_id}' not found.")

    return {
        "id": row["id"],
        "datasetId": row["dataset_id"],
        "title": row["title"],
        "filePath": row["file_path"],
        "createdAt": row["created_at"],
    }


def delete_report(report_id: str) -> dict[str, str]:
    """Delete a report and its associated files."""
    report = get_report(report_id)

    # Delete file
    file_path = Path(report["filePath"])
    if file_path.exists():
        file_path.unlink()
        # Clean up HTML companion file
        html_path = file_path.with_suffix(".html")
        if html_path.exists():
            html_path.unlink()

    # Delete from database
    with db_session() as conn:
        conn.execute("DELETE FROM reports WHERE id = ?", (report_id,))

    return {"message": "Report deleted successfully."}

