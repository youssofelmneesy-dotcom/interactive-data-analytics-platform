def generate_pdf_report(
    dataset_id: str,
    title: str,
    sections: list[dict[str, Any]],
) -> str:
    """Generate a PDF report and return the file path.

    Args:
        dataset_id: Dataset identifier.
        title: Report title.
        sections: List of report sections.

    Returns:
        Path to the generated PDF file.

    Raises:
        InternalServerError: If PDF generation fails.
    """
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        raise InternalServerError("Playwright not installed. Run: pip install playwright && playwright install")

    # Build HTML report
    html_content = _build_report_html(dataset_id, title, sections)

    # Create output directory
    report_dir = Path("reports") / dataset_id
    report_dir.mkdir(parents=True, exist_ok=True)

    report_id = str(uuid.uuid4())
    html_path = report_dir / f"{report_id}.html"
    pdf_path = report_dir / f"{report_id}.pdf"

    # Write HTML file
    html_path.write_text(html_content, encoding="utf-8")

    # Generate PDF using Playwright
    try:
        with sync_playwright() as p:
            browser = p.chromium.launch()
            page = browser.new_page()
            page.goto(f"file://{html_path.absolute()}")
            page.pdf(
                path=str(pdf_path),
                format="A4",
                margin={"top": "20px", "right": "20px", "bottom": "20px", "left": "20px"},
                print_background=True,
            )
            browser.close()
    except Exception as exc:
        raise InternalServerError(f"PDF generation failed: {exc}") from exc

    # Store report metadata in database
    created_at = datetime.now(timezone.utc).isoformat()
    with db_session() as conn:
        conn.execute(
            """
            INSERT INTO reports (id, dataset_id, title, file_path, created_at)
            VALUES (?, ?, ?, ?, ?)
            """,
            (report_id, dataset_id, title, str(pdf_path), created_at),
        )

    return str(pdf_path)


