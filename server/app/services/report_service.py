def _build_insight_html(insight: dict[str, Any]) -> str:
    """Build HTML for a single insight card."""
    severity = insight.get("severity", "info")
    severity_class = f"severity-{severity}"
    return f"""
    <div class="insight-card">
        <span class="severity {severity_class}">{severity.upper()}</span>
        <h3>{insight["title"]}</h3>
        <p>{insight["description"]}</p>
    </div>
    """


def _build_table_html(df, max_rows: int = 20):
    """Build HTML table from DataFrame."""
    preview_df = df.head(max_rows)
    headers = "".join(f"<th>{col}</th>" for col in preview_df.columns)
    rows = ""
    for _, row in preview_df.iterrows():
        row_html = "".join(f"<td>{val}</td>" for val in row.values)
        rows += f"<tr>{row_html}</tr>"
    return headers, rows


def _build_report_html(
    dataset_id: str,
    title: str,
    sections: list[dict[str, Any]],
) -> str:
    """Build complete HTML report content."""
    import pandas as pd
    import base64

    dataset = get_dataset(dataset_id)
    df = get_dataset_dataframe(dataset_id)

    # Build sections HTML
    sections_html = ""
    for section in sections:
        section_type = section.get("type", "text")
        section_title = section.get("title", "Untitled Section")

        if section_type == "summary":
            numeric_cols = df.select_dtypes(include=["number"]).columns.tolist()
            cat_cols = df.select_dtypes(include=["object", "category", "string"]).columns.tolist()
            sections_html += SECTION_TEMPLATES["summary"].format(
                row_count=len(df),
                column_count=len(df.columns),
                numeric_count=len(numeric_cols),
                categorical_count=len(cat_cols),
                description=section.get("content", "Dataset analysis report."),
            )

        elif section_type == "insight":
            insights = list_insights(dataset_id)
            if section.get("insightId"):
                insights = [i for i in insights if i["id"] == section["insightId"]]
            insights_html = "".join(_build_insight_html(i) for i in insights[:10])
            sections_html += SECTION_TEMPLATES["insight"].format(
                title=section_title,
                insights=insights_html,
            )

        elif section_type == "chart":
            chart_id = section.get("chartId")
            if chart_id:
                from app.services.chart_service import get_chart_config
                try:
                    chart_config = get_chart_config(chart_id)
                    chart_data = generate_chart(
                        dataset_id=dataset_id,
                        chart_type=chart_config["chartType"],
                        x_axis=chart_config.get("xAxis"),
                        y_axis=chart_config.get("yAxis"),
                        aggregation=chart_config.get("aggregation", "count"),
                        group_by=chart_config.get("groupBy"),
                        filters=chart_config.get("filters"),
                        title=chart_config.get("title"),
                    )
                    # Generate SVG from chart data using recharts-like SVG
                    svg_content = _generate_chart_svg(chart_data)
                    svg_base64 = base64.b64encode(svg_content.encode()).decode()
                    sections_html += SECTION_TEMPLATES["chart"].format(
                        title=section_title,
                        chart_title=chart_config.get("title", "Chart"),
                        svg_base64=svg_base64,
                    )
                except Exception:
                    sections_html += f'<div class="section"><h2>{section_title}</h2><p>Chart could not be rendered.</p></div>'

        elif section_type == "table":
            headers, rows = _build_table_html(df, max_rows=20)
            sections_html += SECTION_TEMPLATES["table"].format(
                title=section_title,
                headers=headers,
                rows=rows,
            )

        elif section_type == "text":
            sections_html += SECTION_TEMPLATES["text"].format(
                title=section_title,
                content=section.get("content", ""),
            )

    # Assemble full report
    html = REPORT_TEMPLATE.replace("{{title}}", title)
    html = html.replace("{{generated_at}}", datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"))
    html = html.replace("{{dataset_name}}", dataset["name"])
    html = html.replace("{{row_count}}", str(dataset["rowCount"]))
    html = html.replace("{{column_count}}", str(dataset["columnCount"]))
    html = html.replace("{{app_version}}", settings.app_version)
    html = html.replace("{{sections}}", sections_html)

    return html


def _generate_chart_svg(chart_data: dict[str, Any]) -> str:
    """Generate a simple SVG representation of chart data for PDF embedding."""
    data = chart_data.get("data", [])
    chart_type = chart_data.get("chartType", "bar")
    title = chart_data.get("config", {}).get("title", "Chart")

    if not data:
        return f'<svg xmlns="http://www.w3.org/2000/svg" width="600" height="300"><text x="300" y="150" text-anchor="middle">No data</text></svg>'

    # Simple bar chart SVG
    width = 600
    height = 300
    margin = {"top": 40, "right": 20, "bottom": 60, "left": 60}
    chart_width = width - margin["left"] - margin["right"]
    chart_height = height - margin["top"] - margin["bottom"]

    # Extract values
    if chart_type == "pie":
        values = [d.get("value", 0) for d in data]
        labels = [d.get("name", "") for d in data]
    elif chart_type == "histogram":
        values = [d.get("count", 0) for d in data]
        labels = [d.get("label", "") for d in data]
    else:
        values = [d.get(list(d.keys())[-1], 0) for d in data if isinstance(d, dict)]
        labels = [str(d.get(list(d.keys())[0], "")) for d in data if isinstance(d, dict)]

    if not values:
        return f'<svg xmlns="http://www.w3.org/2000/svg" width="600" height="300"><text x="300" y="150" text-anchor="middle">No valid data</text></svg>'

    max_val = max(values) if values else 1
    bar_width = chart_width / len(values) * 0.8
    bar_gap = chart_width / len(values) * 0.2

    svg_parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}">',
        f'<rect width="{width}" height="{height}" fill="#f9fafb"/>',
        f'<text x="{width/2}" y="25" text-anchor="middle" font-size="16" font-weight="bold" fill="#374151">{title}</text>',
    ]

    # Bars
    for i, (val, label) in enumerate(zip(values, labels)):
        if max_val == 0:
            bar_height = 0
        else:
            bar_height = (val / max_val) * chart_height
        x = margin["left"] + i * (bar_width + bar_gap) + bar_gap / 2
        y = margin["top"] + chart_height - bar_height
        color = f"hsl({222 + (i * 30) % 360}, 60%, 45%)"
        svg_parts.append(f'<rect x="{x}" y="{y}" width="{bar_width}" height="{bar_height}" fill="{color}" rx="3"/>')

        # Label
        label_x = x + bar_width / 2
        label_y = margin["top"] + chart_height + 20
        svg_parts.append(f'<text x="{label_x}" y="{label_y}" text-anchor="middle" font-size="10" fill="#6b7280">{str(label)[:15]}</text>')

    # Y-axis
    svg_parts.append(f'<line x1="{margin["left"]}" y1="{margin["top"]}" x2="{margin["left"]}" y2="{margin["top"] + chart_height}" stroke="#d1d5db" stroke-width="1"/>')
    # X-axis
    svg_parts.append(f'<line x1="{margin["left"]}" y1="{margin["top"] + chart_height}" x2="{width - margin["right"]}" y2="{margin["top"] + chart_height}" stroke="#d1d5db" stroke-width="1"/>')

    # Y-axis labels
    for i in range(5):
        val = max_val * (i / 4)
        y = margin["top"] + chart_height - (i / 4) * chart_height
        svg_parts.append(f'<text x="{margin["left"] - 10}" y="{y + 4}" text-anchor="end" font-size="10" fill="#6b7280">{val:.0f}</text>')

    svg_parts.append("</svg>")
    return "\n".join(svg_parts)


